/*Program which uses the Chars, Integers , Floating point Data Types*/
#include <stdio.h>
int main(){
    printf("I am learning the %c programming language \n", 'C'); // '%c' is used to replace the character. 
    printf("I just completed the chapter %d\n", 2); // '%d' is used to replace the integers
    printf("I am %.1f percent ready to move on", 99.9); // '%f' is used for floating point where as '%.1f' means floating no. with one decimal place!
    printf("Now to the next chapter!");
    return 0;
}
